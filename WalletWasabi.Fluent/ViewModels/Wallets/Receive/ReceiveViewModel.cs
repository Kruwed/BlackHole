using System.Linq;
using System.Reactive.Disposables;
using System.Reactive.Disposables.Fluent;
using System.Reactive.Linq;
using System.Windows.Input;
using Avalonia.Controls;
using DynamicData.Aggregation;
using WalletWasabi.Fluent.Models.Wallets;
using WalletWasabi.Fluent.ViewModels.Navigation;

namespace WalletWasabi.Fluent.ViewModels.Wallets.Receive;

/// <summary>
/// Receiving: a button that generates a new address, and the addresses that were generated and have not been paid to
/// yet. Receive on the main screen of Payjoin in the Coinjoin dialog opens it, and the way back leads there.
/// </summary>
/// <remarks>
/// A wallet that came back from its backup generates no address before it has gone through the chain: until then it
/// does not know which of its addresses were used, and where it is to go on. The button waits, and the page says why.
/// </remarks>
[NavigationMetaData(Title = "Receive", NavigationTarget = NavigationTarget.DialogScreen)]
public partial class ReceiveViewModel : RoutableViewModel
{
	private readonly IWalletModel _wallet;

	[AutoNotify] private FlatTreeDataGridSource<AddressViewModel> _source = new(Enumerable.Empty<AddressViewModel>());
	[AutoNotify(SetterModifier = AccessModifier.Private)] private bool _hasAddresses;

	/// <summary>Whether an address can be generated at the moment.</summary>
	[AutoNotify(SetterModifier = AccessModifier.Private)] private bool _canGenerate;

	public ReceiveViewModel(UiContext uiContext, IWalletModel wallet) : base(uiContext)
	{
		_wallet = wallet;

		SetupCancel(enableCancel: true, enableCancelOnEscape: true, enableCancelOnPressed: true);
		EnableBack = true;

		// Every address is one that was not given out before. It is shown right away, and it joins the list.
		// The page has no button that the Enter key presses: an address is only generated by a click on this one.
		_canGenerate = _wallet.Addresses.CanGiveOutAddress;
		GenerateCommand = ReactiveCommand.Create(Generate, this.WhenAnyValue(x => x.CanGenerate));
	}

	/// <summary>Generates a new address and shows it.</summary>
	public ICommand GenerateCommand { get; }

	/// <summary>Why no address can be generated while none can.</summary>
	public string WaitMessage => WalletWasabi.Blockchain.Keys.KeyManager.AddressSearchMessage;

	protected override void OnNavigatedTo(bool isInHistory, CompositeDisposable disposables)
	{
		base.OnNavigatedTo(isInHistory, disposables);

		// The wallet knows where its addresses go on once it has gone through the chain, which is when it is loaded.
		CanGenerate = _wallet.Addresses.CanGiveOutAddress;

		_wallet.Loaded
			.ObserveOn(RxApp.MainThreadScheduler)
			.Subscribe(_ => CanGenerate = _wallet.Addresses.CanGiveOutAddress)
			.DisposeWith(disposables);

		_wallet.Addresses.Unused
			.ToObservableChangeSet()
			.Transform(address => new AddressViewModel(UiContext, ShowAddress, address))
			.DisposeMany()
			.Bind(out var unusedAddresses)
			.Subscribe()
			.DisposeWith(disposables);

		_wallet.Addresses.Unused
			.ToObservableChangeSet()
			.Count()
			.Select(count => count > 0)
			.ObserveOn(RxApp.MainThreadScheduler)
			.BindTo(this, x => x.HasAddresses)
			.DisposeWith(disposables);

		var source = ReceiveAddressesDataGridSource.Create(unusedAddresses);
		source.RowSelection!.SingleSelect = true;
		source.DisposeWith(disposables);

		Source = source;
	}

	private void Generate()
	{
		// The wallet may have set out on its way through the chain since the page looked the last time.
		CanGenerate = _wallet.Addresses.CanGiveOutAddress;

		if (CanGenerate)
		{
			ShowAddress(_wallet.Addresses.NextReceiveAddress());
		}
	}

	/// <summary>Shows an address with its QR code, on a page of its own. The way back from there leads here.</summary>
	private void ShowAddress(IAddress address)
	{
		Navigate().To().ReceiveAddress(_wallet, address);
	}
}
